//! Deterministic fuzzing for every parser in the gateway that eats
//! attacker-controlled bytes.
//!
//! `cargo-fuzz`/libFuzzer needs nightly, which this project does not have, so
//! this is a self-contained harness: a seeded xorshift + a corpus of hand-written
//! nasty cases + structure-aware mutations, run in-process against the *real*
//! parsers out of the library. It is an integration test on purpose, so plain
//! `cargo test` exercises it.
//!
//! What is asserted for every single iteration:
//!
//! * **no panic.** The parser call runs under `catch_unwind`; a panic is recorded
//!   with the exact input in hex and fails the test.
//! * **no unbounded allocation.** A `#[global_allocator]` wrapper counts bytes
//!   allocated on the fuzzing thread; a single iteration may not allocate more
//!   than the target's documented cap (8 MiB, or the RESP reply budget for the
//!   Redis decoder, whose *legal* maximum is 8 MiB of bulk).
//! * **bounded work / bounded state.** Whatever the parser exposes is checked
//!   against its documented bound: the SSE buffer against `MAX_EVENT_BYTES`,
//!   WebSocket payloads against the frame/message caps, media and JSON spans
//!   against the input length, translated SSE output against a multiple of the
//!   input, and the number of frames/messages a reader will deliver.
//! * **agreement between two implementations**: WebSocket encode -> decode
//!   round-trip, `encode_command` -> reply-decoder round-trip, SSE chunk-split
//!   independence, and translated SSE fed back through the shared SSE parser.
//!   These are the oracles that find semantic bugs, not just crashes.
//!
//! Inputs are generated by mutating *valid* seeds (bit flips, byte stomps,
//! truncation, deletion, duplication, corpus splicing, hostile length prefixes),
//! because structural mutation reaches code paths random bytes never do. Stream
//! parsers additionally get their input split at pseudo-random offsets, so chunk
//! boundaries land inside CRLF pairs, inside `data:` lines and inside the WebSocket
//! header.
//!
//! Run the full campaign (this is the number `docs/FUZZING.md` reports):
//!
//! ```text
//! ANYHOP_FUZZ_ITERS=200000 cargo test --test fuzz_parsers -- --nocapture
//! ```
//!
//! Without the variable each target runs `DEFAULT_ITERS` inputs, which keeps the
//! default `cargo test` fast while still covering every corpus entry and every
//! mutator.

