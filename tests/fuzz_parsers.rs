fn scan_exercise(bytes: &[u8]) {
    if let Some((model, _stream)) = peek_request(bytes) {
        // Unescaping/lossy-UTF-8 can expand a byte to at most 3 bytes (U+FFFD).
        assert!(
            model.len() <= bytes.len().saturating_mul(4) + 16,
            "decoded model of {} bytes from {} input bytes",
            model.len(),
            bytes.len()
        );
    }
    for key in [&b"model"[..], b"stream", b"", b"model_id"] {
        if let Some(span) = string_field_span(bytes, key) {
            assert!(
                span.start <= span.end && span.end <= bytes.len(),
                "span {span:?} outside a {} byte body",
                bytes.len()
            );
            assert!(bytes[span].len() <= bytes.len());
        }
    }
}

