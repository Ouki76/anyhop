/// Iterations per target when `ANYHOP_FUZZ_ITERS` is unset. Small enough that
/// `cargo test` stays interactive; the long campaign is opt-in.
const DEFAULT_ITERS: usize = 2_000;

/// Per-iteration allocation cap for the parsers whose working set is bounded by
/// their own 1 MiB frame/event caps.
const ALLOC_CAP: usize = 8 << 20;

/// The RESP decoder's documented whole-reply budget is 32 MiB; a legal reply can
/// legitimately allocate an 8 MiB bulk, so the cap is the budget plus slack.
const REDIS_ALLOC_CAP: usize = (32 << 20) + (1 << 20);

fn iters() -> usize {
    std::env::var("ANYHOP_FUZZ_ITERS")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
        .filter(|n| *n > 0)
        .unwrap_or(DEFAULT_ITERS)
}

struct Finding {
    kind: &'static str,
    input: Vec<u8>,
    detail: String,
}

struct Report {
    target: &'static str,
    iterations: usize,
    alloc_cap: usize,
    peak_alloc: usize,
    over_cap: usize,
    findings: Vec<Finding>,
    elapsed: Duration,
}

impl Report {
    fn record(&mut self, input: &[u8], iteration: Iteration) {
        self.peak_alloc = self.peak_alloc.max(iteration.allocated);
        if iteration.allocated > self.alloc_cap {
            self.over_cap += 1;
            self.note(
                "over-allocation",
                input,
                format!(
                    "one iteration allocated {} bytes (cap {})",
                    iteration.allocated, self.alloc_cap
                ),
            );
        }
        if let Some(detail) = iteration.panic {
            self.note("panic", input, detail);
        }
    }

    fn note(&mut self, kind: &'static str, input: &[u8], detail: String) {
        // Keep the report readable when a single input panics in many ways; the
        // count still reflects every occurrence.
        if self.findings.len() < 12 {
            self.findings.push(Finding {
                kind,
                input: input.to_vec(),
                detail,
            });
        }
    }

    fn finish(self) {
        let seconds = self.elapsed.as_secs_f64().max(1e-9);
        println!(
            "fuzz {:<22} {:>7} iterations in {:>7.2}s ({:>8.0}/s)  peak {:>7.1} KiB/iter",
            self.target,
            self.iterations,
            seconds,
            self.iterations as f64 / seconds,
            self.peak_alloc as f64 / 1024.0,
        );
        assert!(
            self.findings.is_empty(),
            "{}: {} finding(s) in {} iterations\n{}",
            self.target,
            self.findings.len(),
            self.iterations,
            self.render(),
        );
    }

    fn render(&self) -> String {
        let mut out = String::new();
        for finding in &self.findings {
            out.push_str(&format!(
                "\n  [{}] {}\n    input ({} bytes): {}\n",
                finding.kind,
                finding.detail,
                finding.input.len(),
                hex_preview(&finding.input),
            ));
        }
        if self.over_cap > 0 {
            out.push_str(&format!(
                "\n  over-allocation happened {} time(s)\n",
                self.over_cap
            ));
        }
        out
    }
}

/// Hex of the trigger, truncated for the report (the full input is what the
/// fuzzer generated; anything small enough to be a minimal trigger is fully
/// printed).
fn hex_preview(bytes: &[u8]) -> String {
    const SHOWN: usize = 512;
    let mut out = hex::encode(&bytes[..bytes.len().min(SHOWN)]);
    if bytes.len() > SHOWN {
        out.push_str(&format!("… (+{} bytes)", bytes.len() - SHOWN));
    }
    out
}

/// Run one target on a worker thread with a watchdog.
///
/// A parser that loops forever would otherwise hang `cargo test`; here it fails
/// the test after a generous multiple of the expected runtime.
fn run_target(
    target: &'static str,
    iterations: usize,
    body: impl FnOnce() -> Report + Send + 'static,
) {
    let (tx, rx) = mpsc::channel();
    let worker = std::thread::Builder::new()
        .name(format!("fuzz-{target}"))
        .spawn(move || {
            let _ = tx.send(body());
        })
        .expect("spawn the fuzz worker");
    // 20x the ~10 µs/iteration the slowest target needs, plus a floor.
    let wait = Duration::from_secs(30 + (iterations as u64) / 2_000);
    match rx.recv_timeout(wait) {
        Ok(report) => {
            let _ = worker.join();
            report.finish();
        }
        Err(_) => panic!(
            "{target}: no result after {wait:?} for {iterations} iterations — \
             a parser is not making progress"
        ),
    }
}

fn drive(
    target: &'static str,
    seed: u64,
    iterations: usize,
    alloc_cap: usize,
    corpus: Vec<Vec<u8>>,
    max_input: usize,
    mut parse: impl FnMut(&[u8]),
) -> Report {
    assert!(!corpus.is_empty(), "{target}: a target needs a corpus");
    let started = Instant::now();
    let mut rng = Rng::new(seed);
    let mut report = Report {
        target,
        iterations,
        alloc_cap,
        peak_alloc: 0,
        over_cap: 0,
        findings: Vec::new(),
        elapsed: Duration::ZERO,
    };
    for _ in 0..iterations {
        let input = mutate(&mut rng, &corpus, max_input);
        let iteration = measure(|| parse(&input));
        report.record(&input, iteration);
    }
    report.elapsed = started.elapsed();
    report
}

/// Split an input at pseudo-random offsets: stream parsers must behave the same
/// however the bytes arrive, and chunk boundaries are where framing bugs live.
fn split_chunks(data: &[u8]) -> Vec<Bytes> {
    let mut rng = Rng::new(fnv1a(data) ^ 0x5d2f_1c3b_9a67_e401);
    let parts = 1 + rng.below(4);
    let mut out = Vec::new();
    let mut rest = data;
    for _ in 0..parts {
        if rest.is_empty() {
            break;
        }
        let n = rng.below(rest.len() + 1);
        let (head, tail) = rest.split_at(n);
        out.push(Bytes::copy_from_slice(head));
        rest = tail;
    }
    if !rest.is_empty() {
        out.push(Bytes::copy_from_slice(rest));
    }
    if out.is_empty() {
        out.push(Bytes::new());
    }
    out
}

