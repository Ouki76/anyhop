/// The fuzz targets must actually reach the *success* path of each parser, not
/// just its error path: these pin the field/value a valid seed yields.
#[test]
fn the_valid_seeds_reach_the_parsers_success_paths() {
    let body = multipart(
        "--X\nContent-Disposition: form-data; name=\"prompt\"\n\nhello\n\
         --X\nContent-Disposition: form-data; name=\"model\"\n\nvendor/model-x\n--X--\n",
    );
    let span = multipart_field_span(&body, "model").expect("the model field is found");
    assert_eq!(&body[span], b"vendor/model-x");

    let request = br#"{"model":"gpt-4o","stream":true,"messages":[]}"#;
    assert_eq!(
        peek_request(request),
        Some(("gpt-4o".to_string(), true)),
        "the scanner's happy path"
    );

    let reply = block_on(reply_from_slice(b"*2\r\n:1\r\n:0\r\n")).expect("a token-bucket reply");
    assert_eq!(reply.as_array().map(|items| items.len()), Some(2));

    let frame = ws_frame(true, 0x1, Some([1, 2, 3, 4]), b"hi");
    assert_eq!(
        &frame[2..6],
        &[1, 2, 3, 4],
        "the masked seed carries its key"
    );
}

/// Guards the fix for the scanner/upstream disagreement this harness reported
/// (see `docs/FUZZING.md`, findings): a duplicate or escaped `model` key used to
/// be resolved by the byte scanner as *first one wins* while `serde_json` — and
/// every upstream parser — resolves it as *last one wins* (and decodes escapes).
/// The gateway authorized one model and the provider executed another.
///
/// The fast path must now decline an ambiguous body, so the caller falls back to a
/// real parse whose answer is the one the upstream will apply.
#[test]
fn ambiguous_model_keys_fall_back_to_a_real_parse() {
    // Duplicate key: the fast path declines...
    let duplicate = br#"{"model":"allowed","messages":[],"model":"disabled"}"#;
    assert_eq!(
        peek_request(duplicate),
        None,
        "a duplicated model key is ambiguous"
    );
    assert_eq!(
        string_field_span(duplicate, b"model"),
        None,
        "and must not be spliced by span"
    );
    // ...and the fallback resolves what the upstream will resolve.
    let parsed: Value = serde_json::from_slice(duplicate).expect("valid JSON");
    assert_eq!(parsed["model"], "disabled");

    // The same for an escaped spelling of the key: `"mod\u0065l"` is `model` to
    // serde, so the raw-byte scan must not resolve it either.
    let escaped = br#"{"model":"allowed","mod\u0065l":"disabled"}"#;
    assert_eq!(
        peek_request(escaped),
        None,
        "an escaped spelling of a field name is ambiguous"
    );
    assert_eq!(
        string_field_span(escaped, b"model"),
        None,
        "an escaped model key must never be spliced by span"
    );
    let parsed: Value = serde_json::from_slice(escaped).expect("valid JSON");
    assert_eq!(parsed["model"], "disabled");

    // A single plain key still takes the fast path: this is the hot path, and the
    // ambiguity check must not cost it a full parse.
    let plain = br#"{"model":"m","stream":true,"messages":[]}"#;
    assert_eq!(peek_request(plain), Some(("m".to_string(), true)));
    assert_eq!(
        &plain[string_field_span(plain, b"model").expect("span")],
        b"m"
    );

    // A string *value* that happens to be `"model"` is not a key; it may cost the
    // fast path (the scanner is allowed to be conservative) but it must never
    // change which value wins.
    let shadowed = br#"{"model":"real","messages":[{"role":"user","content":"model"}]}"#;
    if let Some((model, _)) = peek_request(shadowed) {
        assert_eq!(model, "real");
    }
}

