// ---------------------------------------------------------------------------
// the meter: bytes allocated per iteration
// ---------------------------------------------------------------------------

thread_local! {
    /// Bytes allocated on this thread while `MEASURING` is set.
    static MEASURED: Cell<usize> = const { Cell::new(0) };
    static MEASURING: Cell<bool> = const { Cell::new(false) };
}

/// Counts allocations so one fuzz iteration can be charged for what it holds.
///
/// Per-thread counters, not a global atomic: `cargo test` runs the targets in
/// parallel, and one target's allocations must not be billed to another.
struct MeteredAlloc;

#[allow(unsafe_code)]
unsafe impl GlobalAlloc for MeteredAlloc {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        meter(layout.size());
        unsafe { System.alloc(layout) }
    }

    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        meter(layout.size());
        unsafe { System.alloc_zeroed(layout) }
    }

    unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
        meter(new_size);
        unsafe { System.realloc(ptr, layout, new_size) }
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        unsafe { System.dealloc(ptr, layout) }
    }
}

#[global_allocator]
static GLOBAL: MeteredAlloc = MeteredAlloc;

/// `try_with`, because the allocator also runs while thread locals are torn down.
#[inline]
fn meter(n: usize) {
    let _ = MEASURING.try_with(|on| {
        if on.get() {
            let _ = MEASURED.try_with(|total| total.set(total.get().saturating_add(n)));
        }
    });
}

/// What one iteration did.
struct Iteration {
    panic: Option<String>,
    allocated: usize,
}

/// Run one parser invocation with allocation counting and panic catching.
fn measure(f: impl FnOnce()) -> Iteration {
    MEASURED.with(|total| total.set(0));
    MEASURING.with(|on| on.set(true));
    let caught = catch_unwind(AssertUnwindSafe(f));
    MEASURING.with(|on| on.set(false));
    Iteration {
        panic: caught.err().map(|payload| panic_text(payload.as_ref())),
        allocated: MEASURED.with(Cell::get),
    }
}

fn panic_text(payload: &(dyn Any + Send)) -> String {
    if let Some(s) = payload.downcast_ref::<&'static str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else {
        "<non-string panic payload>".to_string()
    }
}

