fn responses_exercise(bytes: &[u8]) {
    let Ok(value) = serde_json::from_slice::<Value>(bytes) else {
        return;
    };
    if let Ok(chat) = to_chat_request(&value) {
        assert!(
            chat.get("model").and_then(Value::as_str).is_some(),
            "a translated request always carries a model"
        );
        let messages = chat
            .get("messages")
            .and_then(Value::as_array)
            .expect("a translated request always carries messages");
        assert!(!messages.is_empty(), "no empty message list may be built");
        for message in messages {
            assert!(
                message.get("role").and_then(Value::as_str).is_some(),
                "every translated message carries a role"
            );
            assert!(
                message.get("content").is_some(),
                "every translated message carries content"
            );
        }
        // The replay builder must keep that shape when it prepends history.
        //
        // The stored turn is replayed *verbatim*: `StoredResponse::input` is
        // written by the gateway from an already-translated request, so the
        // builder is not a second validator and must not rewrite it. (The first
        // version of this target asserted every replayed message carries a role;
        // that was the harness over-specifying, not a parser bug — a corrupted
        // store is not attacker-reachable.)
        let previous = stored_response(&value);
        let stored: Vec<Value> = match &previous.input {
            Value::Array(items) => items.clone(),
            Value::String(text) => vec![serde_json::json!({"role": "user", "content": text})],
            _ => Vec::new(),
        };
        let mut replay = chat.clone();
        replay_history(&mut replay, &previous);
        let replayed = replay["messages"]
            .as_array()
            .expect("replay keeps a message array");
        assert_eq!(
            replayed.len(),
            stored.len() + 1 + messages.len(),
            "replay prepends the stored turn and one assistant message"
        );
        assert_eq!(
            &replayed[..stored.len()],
            stored.as_slice(),
            "stored history is replayed verbatim"
        );
        assert_eq!(replayed[stored.len()]["role"], "assistant");
        assert_eq!(
            replayed[stored.len()]["content"],
            previous.output_text,
            "the assistant turn carries the stored answer"
        );
        assert_eq!(
            &replayed[stored.len() + 1..],
            messages.as_slice(),
            "the new turn is appended unchanged"
        );
    }
}

