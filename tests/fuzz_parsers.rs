const WS_MAX_FRAME: usize = 4 * 1024;
const WS_MAX_MESSAGE: usize = 8 * 1024;
const WS_MAX_DELIVERED: usize = 4 * 1024;

/// Build a wire frame. `mask: None` = server→client (unmasked).
fn ws_frame(fin: bool, opcode: u8, mask: Option<[u8; 4]>, payload: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    out.push(if fin { 0x80 } else { 0 } | opcode);
    let mask_bit = if mask.is_some() { 0x80 } else { 0 };
    if payload.len() < 126 {
        out.push(mask_bit | payload.len() as u8);
    } else {
        out.push(mask_bit | 126);
        out.extend_from_slice(&(payload.len() as u16).to_be_bytes());
    }
    match mask {
        Some(key) => {
            out.extend_from_slice(&key);
            out.extend(payload.iter().enumerate().map(|(i, b)| b ^ key[i & 3]));
        }
        None => out.extend_from_slice(payload),
    }
    out
}

fn ws_corpus() -> Vec<Vec<u8>> {
    const KEY: [u8; 4] = [0x37, 0xfa, 0x21, 0x3d];
    let mut fragments = ws_frame(true, 0x1, Some(KEY), b"frag-");
    fragments.extend_from_slice(&ws_frame(false, 0x0, Some(KEY), b"ment"));
    fragments.extend_from_slice(&ws_frame(true, 0x0, Some(KEY), b"ed"));

    let mut many_continuations = ws_frame(false, 0x1, Some(KEY), b"a");
    for _ in 0..300 {
        many_continuations.extend_from_slice(&ws_frame(false, 0x0, Some(KEY), b"b"));
    }
    many_continuations.extend_from_slice(&ws_frame(true, 0x0, Some(KEY), b"c"));

    vec![
        // Valid traffic, both directions, every opcode.
        Vec::new(),
        vec![0x00],
        vec![0xFF; 16],
        vec![0xFF; 512],
        ws_frame(true, 0x1, Some(KEY), b"hi"),
        ws_frame(true, 0x1, None, b"hi"),
        ws_frame(true, 0x2, Some(KEY), &[0u8; 200]),
        ws_frame(true, 0x9, Some(KEY), b"ping"),
        ws_frame(true, 0xA, Some(KEY), b"pong"),
        ws_frame(true, 0x8, Some(KEY), &[0x03, 0xE8]),
        ws_frame(true, 0x8, Some(KEY), b""),
        fragments.clone(),
        many_continuations,
        // Hostile headers: reserved bits, unknown opcodes, control rules.
        vec![0xC1, 0x00],
        vec![0x91, 0x00],
        vec![0x8F, 0x00],
        vec![0x09, 0x00],
        vec![0x89, 0x01, 0x41],
        // Length prefixes the peer must never make us allocate for.
        vec![0x81, 0xFE, 0xFF, 0xFF],
        vec![0x81, 0xFF, 0x80, 0, 0, 0, 0, 0, 0, 0],
        vec![0x81, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF],
        vec![0x81, 0xFF, 0x00, 0, 0, 0, 0x00, 0x01, 0x00, 0x00],
        vec![0x81, 0x7F, 0x01],
        // Masking rule violations, in both directions.
        vec![0x81, 0x80],
        vec![0x81, 0x82, 1, 2, 3, 4, b'h'],
        // Payload rules: bad UTF-8, one-byte close, reserved close codes.
        ws_frame(true, 0x1, None, &[0xC3, 0x28]),
        ws_frame(true, 0x1, Some(KEY), &[0xED, 0xA0, 0x80]),
        ws_frame(true, 0x8, None, &[0x03]),
        ws_frame(true, 0x8, None, &[0x03, 0xED]),
        ws_frame(true, 0x8, None, &[0x00, 0x00]),
        ws_frame(true, 0x8, None, &[0x0B, 0xB8]),
        // Continuation without a start, and a new message mid-fragment.
        {
            let mut v = ws_frame(true, 0x0, Some(KEY), b"orphan");
            v.extend_from_slice(&fragments);
            v
        },
        {
            let mut v = ws_frame(true, 0x1, Some(KEY), b"one");
            v.extend_from_slice(&ws_frame(true, 0x1, Some(KEY), b"two"));
            v
        },
        // Valid prefix, then garbage.
        {
            let mut v = ws_frame(true, 0x1, Some(KEY), b"ok");
            v.extend_from_slice(&[0xDE, 0xAD, 0xBE, 0xEF]);
            v
        },
    ]
}

/// Read every message a peer would get out of `bytes`, and validate each one.
fn ws_drain(bytes: &[u8], mask: Mask) {
    let mut reader = FrameReader::with_limits(bytes, mask, WS_MAX_FRAME, WS_MAX_MESSAGE);
    let mut delivered = 0usize;
    loop {
        match block_on(reader.next_message()) {
            Ok(Some(frame)) => {
                delivered += 1;
                assert!(
                    delivered <= WS_MAX_DELIVERED,
                    "delivered {delivered} messages from {} bytes",
                    bytes.len()
                );
                assert!(
                    frame.payload.len() <= WS_MAX_MESSAGE,
                    "message of {} bytes exceeds the {WS_MAX_MESSAGE} byte cap",
                    frame.payload.len()
                );
                // `next_message` only ever yields finished data messages or
                // control frames, which are final by definition.
                assert!(frame.fin, "next_message yielded an unfinished frame");
            }
            Ok(None) | Err(_) => return,
        }
    }
}

/// The write half: a small payload must encode to exactly header + payload with
/// no mask bit (the server→client direction).
fn ws_encode(bytes: &[u8]) {
    let frame = Frame::binary(bytes.to_vec());
    let mut wire = Vec::new();
    block_on(write_frame(&mut wire, &frame)).expect("a frame under the cap must encode");
    let header = if bytes.len() < 126 {
        2
    } else if bytes.len() <= usize::from(u16::MAX) {
        4
    } else {
        10
    };
    assert_eq!(wire.len(), header + bytes.len(), "frame length");
    assert_eq!(wire[0], 0x82, "FIN|binary opcode");
    assert_eq!(wire[1] & 0x80, 0, "server frames must not be masked");
    assert_eq!(wire[1] & 0x7F, bytes.len().min(126) as u8, "length field");
}

/// Both halves must agree: what `write_frame*` puts on the wire, `FrameReader`
/// must hand back byte for byte — in the masked direction too, where the XOR is
/// applied on one side and undone on the other.
fn ws_round_trip(bytes: &[u8]) {
    for masked in [false, true] {
        let frame = Frame::binary(bytes.to_vec());
        let mut wire = Vec::new();
        if masked {
            block_on(write_frame_masked(&mut wire, &frame)).expect("a small frame encodes masked");
        } else {
            block_on(write_frame(&mut wire, &frame)).expect("a small frame encodes unmasked");
        }
        let policy = if masked {
            Mask::Required
        } else {
            Mask::Forbidden
        };
        let mut reader = FrameReader::new(&wire[..], policy);
        let decoded = block_on(reader.next_frame())
            .unwrap_or_else(|e| panic!("the frame we just encoded does not decode: {e}"));
        assert_eq!(
            decoded.payload, bytes,
            "encode/decode round trip changed the payload"
        );
        assert_eq!(decoded.opcode, OpCode::Binary);
        assert!(decoded.fin);
    }
}

/// The realtime handshake pushes bytes that arrived in the same read as the HTTP
/// head back in front of the first frame; that merge must not corrupt framing.
fn ws_prepend(bytes: &[u8]) {
    let split = bytes.len() / 2;
    let (head, tail) = bytes.split_at(split);
    let mut reader = FrameReader::with_limits(tail, Mask::Required, WS_MAX_FRAME, WS_MAX_MESSAGE);
    reader.prepend(head);
    let mut delivered = 0usize;
    loop {
        match block_on(reader.next_message()) {
            Ok(Some(frame)) => {
                delivered += 1;
                assert!(delivered <= WS_MAX_DELIVERED);
                assert!(frame.payload.len() <= WS_MAX_MESSAGE);
            }
            Ok(None) | Err(_) => return,
        }
    }
}

fn ws_exercise(bytes: &[u8]) {
    ws_drain(bytes, Mask::Required);
    ws_drain(bytes, Mask::Forbidden);
    ws_encode(bytes);
    ws_round_trip(bytes);
    ws_prepend(bytes);
}

