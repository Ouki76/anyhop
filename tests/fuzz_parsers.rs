/// The translated stream must be well-formed SSE made of whole UTF-8 JSON frames.
fn check_translated(frames: &[Bytes], input_len: usize) {
    assert!(
        frames.len() <= 4096,
        "{} translated frames from {input_len} input bytes",
        frames.len()
    );
    let mut total = 0usize;
    for frame in frames {
        std::str::from_utf8(frame).expect("every translated frame is UTF-8");
        assert!(
            frame.ends_with(b"\n\n"),
            "every translated frame is SSE-terminated"
        );
        total = total.saturating_add(frame.len());
    }
    // Re-encoding a payload cannot explode it: a few times the input at most.
    assert!(
        total <= 4 << 20,
        "translated output of {total} bytes from {input_len} input bytes"
    );

    // The client parses this stream with an SSE parser, so what we emit must be
    // exactly one complete event per frame, and every event but `[DONE]` must be
    // JSON. This is the round trip `sse::frame` -> `SseParser`.
    let mut joined = Vec::with_capacity(total);
    for frame in frames {
        joined.extend_from_slice(frame);
    }
    let mut parser = SseParser::new();
    let mut events = parser.feed(&joined);
    events.extend(parser.finish());
    assert_eq!(
        events.len(),
        frames.len(),
        "{} frames re-parsed as {} events",
        frames.len(),
        events.len()
    );
    for event in &events {
        if event.as_ref() == b"[DONE]" {
            continue;
        }
        serde_json::from_slice::<Value>(event)
            .unwrap_or_else(|e| panic!("a translated event is not JSON ({e}): {event:?}"));
    }
}

fn collect_frames<S>(translated: S) -> Vec<Bytes>
where
    S: futures::Stream<Item = Result<Bytes, io::Error>>,
{
    block_on(translated.collect::<Vec<_>>())
        .into_iter()
        .map(|item| item.expect("the translators report upstream errors as frames"))
        .collect()
}

fn sse_payload(events: &[&str]) -> Vec<u8> {
    let mut out = Vec::new();
    for event in events {
        out.extend_from_slice(format!("data: {event}\n\n").as_bytes());
    }
    out
}

