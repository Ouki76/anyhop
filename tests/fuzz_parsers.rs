fn redis_corpus() -> Vec<Vec<u8>> {
    let mut nested = Vec::new();
    for _ in 0..12 {
        nested.extend_from_slice(b"*2\r\n*2\r\n");
    }
    nested.extend_from_slice(b":0\r\n");
    let mut deep = Vec::new();
    for _ in 0..40 {
        deep.extend_from_slice(b"*1\r\n");
    }
    deep.extend_from_slice(b":1\r\n");
    let mut many = b"*1024\r\n".to_vec();
    for i in 0..1024 {
        many.extend_from_slice(format!(":{i}\r\n").as_bytes());
    }
    vec![
        // Every reply type, including the two nils.
        b"+OK\r\n".to_vec(),
        b"$5\r\nab\r\n".to_vec(),
        b"*2\r\n:1\r\n:0\r\n".to_vec(),
        many,
        b"*-1\r\n".to_vec(),
        b"$-1\r\n".to_vec(),
        // Booleans/maps/sets are RESP3: we speak RESP2 and must refuse them.
        b"_\r\n".to_vec(),
        b"%1\r\n+a\r\n+b\r\n".to_vec(),
        b"~2\r\n:1\r\n:2\r\n".to_vec(),
        b",1.5\r\n".to_vec(),
        b"#t\r\n".to_vec(),
        // Truncation, empty lines, unknown tags, non-UTF-8.
        Vec::new(),
        vec![0x00],
        b"\r\n".to_vec(),
        b"+".to_vec(),
        b"+OK".to_vec(),
        b"$5\r\nab".to_vec(),
        b"$5\r\nabcd\r\n".to_vec(),
        b":1".to_vec(),
        b":\r\n".to_vec(),
        b"?nope\r\n".to_vec(),
        b"+\xFF\xFE\r\n".to_vec(),
        // Hostile numbers: negative lengths, u64::MAX, overflow, leading signs.
        b"$-2\r\n".to_vec(),
        b"$18446744073709551615\r\n".to_vec(),
        b"$9223372036854775808\r\n".to_vec(),
        b"*-2\r\n".to_vec(),
        b"*18446744073709551615\r\n".to_vec(),
        b"*999999999999\r\n".to_vec(),
        b":9223372036854775808\r\n".to_vec(),
        b":-9223372036854775809\r\n".to_vec(),
        b":+1\r\n".to_vec(),
        b":0x10\r\n".to_vec(),
        // Lengths that pass the cap but have no body.
        b"$8388608\r\n".to_vec(),
        b"$8388607\r\n".to_vec(),
        // Nesting at and past the depth cap.
        nested,
        deep,
        // Valid prefix + garbage, and a line with no terminator at all.
        b"+OK\r\nGARBAGE".to_vec(),
        b"*1025\r\n".to_vec(),
        b"+\xff".to_vec(),
        b"\r\n\r\n\r\n".to_vec(),
    ]
}

fn redis_exercise(bytes: &[u8]) {
    match block_on(reply_from_slice(bytes)) {
        Ok(reply) => {
            // The accessors and the log summary must be total over every shape a
            // hostile server can produce.
            let _ = reply.summary();
            let _ = reply.as_integer();
            let _ = reply.as_str();
            let _ = reply.as_bytes();
            let _ = reply.as_array();
        }
        Err(err) => {
            let _ = err.keeps_connection();
            let _ = err.to_string();
        }
    }
    redis_encode(bytes);
}

fn redis_encode(bytes: &[u8]) {
    // A few argv entries (empty entries included: `$0\r\n\r\n` is legal).
    let mut args: Vec<&[u8]> = Vec::new();
    let mut rest = bytes;
    while !rest.is_empty() && args.len() < 8 {
        let share = (rest.len() / (8 - args.len())).max(1);
        let (head, tail) = rest.split_at(share.min(rest.len()));
        args.push(head);
        rest = tail;
    }
    if bytes.is_empty() {
        args.push(b"");
    }
    let wire = encode_command(&args);
    assert!(wire.starts_with(b"*"), "a command is a RESP array");
    assert!(
        wire.len() <= bytes.len() + args.len() * 24 + 8,
        "encoder expanded {} bytes into {}",
        bytes.len(),
        wire.len()
    );
    assert!(wire.ends_with(b"\r\n"), "arguments are CRLF terminated");
    // The encoder emits RESP2 framing, so the decoder must read it back: same
    // number of arguments, same bytes, no truncation at a NUL or a CRLF.
    let reply = block_on(reply_from_slice(&wire)).expect("a command decodes as a RESP array");
    let items = reply.as_array().expect("an array of bulks");
    assert_eq!(items.len(), args.len(), "argument count survives encoding");
    for (item, arg) in items.iter().zip(&args) {
        assert_eq!(
            item.as_bytes(),
            Some(*arg),
            "argument bytes survive encoding"
        );
    }
}

