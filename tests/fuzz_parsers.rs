/// xorshift64: deterministic, dependency-free, and good enough to shuffle inputs.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        // xorshift is stuck at zero.
        Self(seed | 1)
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    fn below(&mut self, n: usize) -> usize {
        if n == 0 {
            0
        } else {
            (self.next_u64() % n as u64) as usize
        }
    }

    fn byte(&mut self) -> u8 {
        self.next_u64() as u8
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }
}

/// FNV-1a, so a chunk split can be derived from the input alone (deterministic
/// without threading an `Rng` through the exercise closures).
fn fnv1a(bytes: &[u8]) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for &b in bytes {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    h
}

/// One input: a corpus entry, then 1–4 edits, truncated to `max_len`.
fn mutate(rng: &mut Rng, corpus: &[Vec<u8>], max_len: usize) -> Vec<u8> {
    let mut out = rng.pick(corpus).clone();
    if out.len() > max_len {
        out.truncate(max_len);
    }
    for _ in 0..(1 + rng.below(4)) {
        edit(rng, &mut out, corpus);
        if out.len() > max_len {
            out.truncate(max_len);
        }
    }
    out
}

fn edit(rng: &mut Rng, out: &mut Vec<u8>, corpus: &[Vec<u8>]) {
    if out.is_empty() {
        out.push(rng.byte());
        return;
    }
    match rng.below(10) {
        0 => {
            let i = rng.below(out.len());
            out[i] ^= 1 << rng.below(8);
        }
        1 => {
            let i = rng.below(out.len());
            out[i] = rng.byte();
        }
        2 => {
            let n = rng.below(out.len() + 1);
            out.truncate(n);
        }
        3 => {
            let i = rng.below(out.len() + 1);
            out.insert(i, rng.byte());
        }
        4 => {
            let i = rng.below(out.len());
            out.remove(i);
        }
        5 => {
            // Duplicate a slice in place: the classic way to double a length
            // field's *declared* payload without growing the real one.
            let a = rng.below(out.len());
            let b = a + rng.below(out.len() - a + 1);
            let piece = out[a..b].to_vec();
            let at = rng.below(out.len() + 1);
            out.splice(at..at, piece);
        }
        6 => {
            let i = rng.below(out.len());
            let n = 1 + rng.below(32);
            for k in 0..n {
                if let Some(b) = out.get_mut(i + k) {
                    *b = 0xFF;
                }
            }
        }
        7 => {
            let other = rng.pick(corpus);
            let a = rng.below(other.len());
            let b = a + rng.below(other.len() - a + 1);
            let at = rng.below(out.len() + 1);
            out.splice(at..at, other[a..b].iter().copied());
        }
        8 => {
            let i = rng.below(out.len());
            let n = 1 + rng.below(64);
            for k in 0..n {
                if let Some(b) = out.get_mut(i + k) {
                    *b = 0x00;
                }
            }
        }
        _ => {
            // Hostile length prefix: a run of decimal digits becomes a number no
            // parser should ever try to allocate for.
            if let Some(i) = out.iter().position(u8::is_ascii_digit) {
                let end = out[i..]
                    .iter()
                    .position(|b| !b.is_ascii_digit())
                    .map_or(out.len(), |k| i + k);
                let digits = if rng.below(2) == 0 {
                    "18446744073709551615"
                } else {
                    "999999999999"
                };
                out.splice(i..end, digits.bytes());
            } else {
                let i = rng.below(out.len());
                out[i] = b'9';
            }
        }
    }
}

