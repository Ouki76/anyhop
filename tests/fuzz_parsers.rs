/// A provider that never frames an event is refused at the documented cap, the
/// buffer is released, and the failure is sticky — the exact three properties the
/// fuzz target checks per iteration, pinned here on a fixed input.
#[test]
fn the_sse_cap_refuses_an_endless_event_and_releases_its_buffer() {
    let mut parser = SseParser::new();
    let chunk = vec![b'a'; 64 * 1024];
    let mut fed = 0usize;
    let mut err = None;
    while err.is_none() {
        match parser.feed_checked(&chunk) {
            Ok(_) => {
                fed += chunk.len();
                assert!(parser.buffered_len() <= MAX_EVENT_BYTES);
                assert!(fed <= MAX_EVENT_BYTES + chunk.len(), "the cap never bit");
            }
            Err(e) => err = Some(e),
        }
    }
    let err = err.expect("the cap bites");
    assert!(err.buffered > MAX_EVENT_BYTES);
    assert_eq!(parser.buffered_len(), 0, "the overrun buffer is released");
    assert!(parser.feed_checked(b"data: ok\n\n").is_err());
    assert!(parser.finish().is_empty());
}

/// A RESP header that announces more than the per-field cap is refused from the
/// header, before the payload is buffered or allocated for.
#[test]
fn redis_refuses_huge_declared_lengths_from_the_header() {
    for wire in [
        &b"$18446744073709551615\r\n"[..],
        b"$9223372036854775808\r\n",
        b"$8388609\r\n",
        b"*18446744073709551615\r\n",
        b"*1025\r\n",
        b"$-2\r\n",
        b"*-2\r\n",
    ] {
        let err = block_on(reply_from_slice(wire)).expect_err("must be refused");
        let text = err.to_string();
        assert!(
            ["exceeds", "negative", "invalid", "too long"]
                .iter()
                .any(|why| text.contains(why)),
            "{wire:?}: {text}"
        );
    }
    // The legal maximum is still accepted, and is a single allocation of the
    // documented size (this is why the Redis allocation cap is not 8 MiB).
    let mut wire = b"$8388608\r\n".to_vec();
    wire.resize(wire.len() + 8 * 1024 * 1024, b'x');
    wire.extend_from_slice(b"\r\n");
    let reply = block_on(reply_from_slice(&wire)).expect("MAX_BULK is legal");
    assert_eq!(reply.as_bytes().map(<[u8]>::len), Some(8 * 1024 * 1024));
}

